export function t(lang, ruta, vars) {
  const partes = ruta.split('.');
  let v = TEXTOS[lang] || TEXTOS.es;
  for (const p of partes) v = v?.[p];
  if (typeof v !== 'string') return ruta;
  if (vars) for (const [k, val] of Object.entries(vars)) v = v.replace(`{${k}}`, String(val));
  return v;
}
